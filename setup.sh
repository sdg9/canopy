#!/bin/bash

# Interactive setup wizard for canopy
# Generates config.sh and optionally creates symlinks

set -e

CANOPY_DIR="$(cd "$(dirname "$0")" && pwd)"
CONFIG_FILE="$CANOPY_DIR/config.sh"

# Helper: ask yes/no with default (overridden by existing config value)
ask() {
  local prompt="$1" default="$2" var="$3"
  local current="${!var}"
  if [ -n "$current" ]; then
    [ "$current" = "true" ] && default="Y" || default="N"
  fi
  if [ "$default" = "Y" ]; then
    read -p "$prompt [Y/n] " answer
    [[ "$answer" =~ ^[Nn]$ ]] && eval "$var=false" || eval "$var=true"
  else
    read -p "$prompt [y/N] " answer
    [[ "$answer" =~ ^[Yy]$ ]] && eval "$var=true" || eval "$var=false"
  fi
}

echo "=== Canopy Setup ==="
echo ""

# Load existing config as defaults
if [ -f "$CONFIG_FILE" ]; then
  echo "Loading existing config as defaults..."
  source "$CONFIG_FILE"
  echo ""
fi

# Check for Homebrew
if ! command -v brew &>/dev/null; then
  echo "Homebrew is required. Install it from https://brew.sh"
  exit 1
fi

echo "--- Dependencies ---"
echo ""

if ! command -v sketchybar &>/dev/null; then
  ask "Sketchybar not found. Install it?" "Y" DO_INSTALL_SKETCHYBAR
  if [ "$DO_INSTALL_SKETCHYBAR" = "true" ]; then
    brew install FelixKratz/formulae/sketchybar
    brew services start sketchybar
  fi
fi

if ! command -v aerospace &>/dev/null; then
  ask "AeroSpace not found. Install it?" "Y" DO_INSTALL_AEROSPACE
  if [ "$DO_INSTALL_AEROSPACE" = "true" ]; then
    brew install --cask nikitabobko/tap/aerospace
  fi
fi

echo ""

echo "--- Built-in Items ---"
echo ""

ask "Enable aerospace workspace indicators?" "Y" ENABLE_AEROSPACE
ask "Enable email indicator?" "Y" ENABLE_EMAIL
ask "Enable Claude usage indicator?" "Y" ENABLE_CLAUDE_USAGE
ask "Enable Slack indicator?" "Y" ENABLE_SLACK
ask "Enable calendar indicators?" "Y" ENABLE_CALENDAR
ask "Enable media controls?" "Y" ENABLE_MEDIA
ask "Enable system monitors (CPU/RAM graphs)?" "Y" ENABLE_SYSTEM

echo ""
echo "--- Plugin Directories ---"
echo ""
if [ -n "$PLUGIN_DIRS" ]; then
  read -p "Plugin directories (space-separated, or empty) [$PLUGIN_DIRS]: " new_plugin_dirs
  PLUGIN_DIRS="${new_plugin_dirs:-$PLUGIN_DIRS}"
else
  read -p "Plugin directories (space-separated, or empty): " PLUGIN_DIRS
fi

# Discover and ask about individual plugins
ENABLED_PLUGINS_PREV=" ${ENABLED_PLUGINS:-} "
ENABLED_PLUGINS=""
if [ -n "$PLUGIN_DIRS" ]; then
  echo ""
  echo "--- Plugins ---"
  echo ""
  for plugin_base in $PLUGIN_DIRS; do
    [ -d "$plugin_base" ] || continue
    for plugin_dir in "$plugin_base"/*/; do
      [ -f "$plugin_dir/item.sh" ] || continue
      plugin_name="$(basename "$plugin_dir")"
      local_var="ENABLE_PLUGIN_${plugin_name}"
      # Default Y if previously enabled or no previous config
      if echo "$ENABLED_PLUGINS_PREV" | grep -q " ${plugin_name} "; then
        default="Y"
      elif [ "$ENABLED_PLUGINS_PREV" = "  " ]; then
        default="Y"
      else
        default="N"
      fi
      ask "Enable $plugin_name plugin?" "$default" "$local_var"
      if [ "${!local_var}" = "true" ]; then
        ENABLED_PLUGINS="${ENABLED_PLUGINS:+$ENABLED_PLUGINS }$plugin_name"
      fi
    done
  done
fi

# Write config.sh
cat > "$CONFIG_FILE" << EOF
#!/bin/bash

# Canopy config — generated by setup.sh

# Left side
ENABLE_AEROSPACE=$ENABLE_AEROSPACE

# Right side
ENABLE_EMAIL=$ENABLE_EMAIL
ENABLE_CLAUDE_USAGE=$ENABLE_CLAUDE_USAGE
ENABLE_SLACK=$ENABLE_SLACK
ENABLE_CALENDAR=$ENABLE_CALENDAR
ENABLE_MEDIA=$ENABLE_MEDIA
ENABLE_SYSTEM=$ENABLE_SYSTEM

# Plugin directories (space-separated)
PLUGIN_DIRS="$PLUGIN_DIRS"

# Enabled plugins (space-separated names)
ENABLED_PLUGINS="$ENABLED_PLUGINS"
EOF

echo ""
echo "Wrote $CONFIG_FILE"

echo ""
echo "--- Symlinks ---"
echo ""

ask "Symlink sketchybar/ -> ~/.config/sketchybar?" "Y" DO_SKETCHYBAR
if [ "$DO_SKETCHYBAR" = "true" ]; then
  mkdir -p ~/.config
  if [ -L ~/.config/sketchybar ]; then
    rm ~/.config/sketchybar
  elif [ -d ~/.config/sketchybar ]; then
    echo "  ~/.config/sketchybar exists and is not a symlink — skipping"
    DO_SKETCHYBAR=false
  fi
  if [ "$DO_SKETCHYBAR" = "true" ]; then
    ln -s "$CANOPY_DIR/sketchybar" ~/.config/sketchybar
    echo "  Linked ~/.config/sketchybar"
  fi
fi

ask "Symlink aerospace.toml -> ~/.aerospace.toml?" "Y" DO_AEROSPACE
if [ "$DO_AEROSPACE" = "true" ]; then
  if [ -L ~/.aerospace.toml ]; then
    rm ~/.aerospace.toml
  elif [ -f ~/.aerospace.toml ]; then
    echo "  ~/.aerospace.toml exists and is not a symlink — skipping"
    DO_AEROSPACE=false
  fi
  if [ "$DO_AEROSPACE" = "true" ]; then
    ln -s "$CANOPY_DIR/aerospace.toml" ~/.aerospace.toml
    echo "  Linked ~/.aerospace.toml"
  fi
fi

echo ""
echo "--- Installing Services ---"
echo ""

if [ "$ENABLE_EMAIL" = "true" ] || [ "$ENABLE_SLACK" = "true" ] || [ "$ENABLE_CALENDAR" = "true" ]; then
  if [ -f "$CANOPY_DIR/mac-status-api/install.sh" ]; then
    echo "  Running: mac-status-api/install.sh"
    (cd "$CANOPY_DIR/mac-status-api" && bash install.sh)
  else
    echo "  mac-status-api/install.sh not found — check $CANOPY_DIR/mac-status-api"
  fi
fi

if [ "$ENABLE_CLAUDE_USAGE" = "true" ]; then
  if [ -f "$CANOPY_DIR/claude-usage-api/install.sh" ]; then
    echo "  Running: claude-usage-api/install.sh"
    (cd "$CANOPY_DIR/claude-usage-api" && bash install.sh)
  else
    echo "  claude-usage-api/install.sh not found — check $CANOPY_DIR/claude-usage-api"
  fi
fi

# --- Plugin Services ---
ENABLED_SET=" ${ENABLED_PLUGINS} "
for plugin_base in $PLUGIN_DIRS; do
  [ -d "$plugin_base" ] || continue
  for plugin_dir in "$plugin_base"/*/; do
    [ -d "$plugin_dir" ] || continue
    plugin_name="$(basename "$plugin_dir")"

    if echo "$ENABLED_SET" | grep -q " ${plugin_name} "; then
      # Enabled plugin — install service if present
      svc_install="$plugin_dir/service/install.sh"
      if [ -f "$svc_install" ]; then
        echo "  Installing service for plugin: $plugin_name"
        (cd "$(dirname "$svc_install")" && bash install.sh)
      fi
    else
      # Disabled plugin — uninstall service if present
      svc_uninstall="$plugin_dir/service/uninstall.sh"
      if [ -f "$svc_uninstall" ]; then
        echo "  Uninstalling service for plugin: $plugin_name"
        (cd "$(dirname "$svc_uninstall")" && bash uninstall.sh)
      fi
    fi
  done
done

echo ""
echo "Done! Restart sketchybar to apply:"
echo "  brew services restart sketchybar"
